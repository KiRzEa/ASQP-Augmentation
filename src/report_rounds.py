"""Write experiments/README.md: rounds, sessions, status and the result of every run (from saved predictions).

    python src/report_rounds.py            # regenerates experiments/README.md
    python src/report_rounds.py --stdout   # print only

Every run is compared with the baseline (outputs/para_none): mean ± sample std over seeds, Δ, Welch p-value
(runs are independent draws; GPU training is not bit-reproducible). No multiple-comparison correction here —
this is a lab notebook, not the paper's table.
"""
import argparse
import glob
import json
import statistics as st
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from asqp_common import load_jsonl, score  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
BASE = "para_none"


def per_seed(run, split):
    out = {}
    for p in sorted(glob.glob(str(ROOT / f"outputs/{run}/seed_*/{split}_predictions.jsonl"))):
        m = score(load_jsonl(p))
        out[Path(p).parent.name] = {"f1": m["quad"]["f1"], **{k: v["f1"] for k, v in m["by_implicit_type"].items()}}
    return out


def welch(a, b):
    try:
        from scipy import stats
        return stats.ttest_ind(b, a, equal_var=False).pvalue
    except Exception:
        return float("nan")


def fmt(xs):
    return f"{st.mean(xs):.2f} ± {st.stdev(xs):.2f}" if len(xs) > 1 else (f"{xs[0]:.2f}" if xs else "–")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdout", action="store_true")
    a = ap.parse_args()
    plan = json.load(open(ROOT / "experiments/rounds.json"))["rounds"]
    base = {s: per_seed(BASE, s) for s in ("dev", "test")}
    lines = ["# Experiments", "", "Generated by `python src/report_rounds.py` from `experiments/rounds.json` and `outputs/`.",
             "Plan: `python3 scripts/kaggle_queue.py plan --round <r>`; Kaggle: `bash scripts/run_kaggle.sh <N>`;",
             "results: put `results_<round>_s<N>.zip` in `runs_inbox/`, `python3 scripts/kaggle_queue.py ingest`, re-run this script.", "",
             "## Rounds", "", "| Round | Goal | Status | Runs |", "|---|---|---|---|"]
    for r, info in plan.items():
        runs = ", ".join(t.get("run", t.get("id", "?")) for t in info["targets"])
        lines.append(f"| {r} | {info['goal']} | {info['status']} | {runs} |")
    lines += ["", "## Runs (Paraphrase ViT5-base, 5 seeds; test F1 unless stated; Δ and Welch p vs baseline)", "",
              "| Round | Run | Seeds | Test F1 | Δ | p | Dev F1 | EA-EO | EA-IO | IA-EO | IA-IO |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r, info in plan.items():
        for tgt in info["targets"]:
            run = tgt.get("run")
            if not run:
                continue
            t, d = per_seed(run, "test"), per_seed(run, "dev")
            if not t:
                lines.append(f"| {r} | {run} | 0 | not run yet | | | | | | | |")
                continue
            tf = [v["f1"] for v in t.values()]
            bf = [v["f1"] for v in base["test"].values()]
            delta = "–" if run == BASE else f"{st.mean(tf) - st.mean(bf):+.2f}"
            p = "–" if run == BASE else f"{welch(bf, tf):.3f}"
            imp = [fmt([v.get(k, 0.0) for v in t.values()]).split(" ±")[0] for k in ("EA-EO", "EA-IO", "IA-EO", "IA-IO")]
            lines.append(f"| {r} | {run} | {len(t)} | {fmt(tf)} | {delta} | {p} | {fmt([v['f1'] for v in d.values()])} | "
                         + " | ".join(imp) + " |")
    text = "\n".join(lines) + "\n"
    if a.stdout:
        print(text)
    else:
        (ROOT / "experiments/README.md").write_text(text)
        print(text)


if __name__ == "__main__":
    main()
